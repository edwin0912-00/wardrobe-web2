#!/usr/bin/env node
// The three receipt schemas have to state the framing bands as literals, because JSON
// Schema cannot read a JS constant, and hand-copying them is how they came to describe a
// pipeline that does not exist: the editorial branches were keyed on mode ids
// (editorial.edwin_novak.organic_contrast) carrying [66, 70] / [62, 70] / [64, 72] /
// [68, 72], while every real preset id is `<mode_id>.<shot_slot>` and the runtime was
// recording the lock-derived [50, 94] / [40, 95] / [50, 95] / [45, 96] / [45, 100] /
// [30, 92] with minimums of 6 / 5 / 5 / 4 / 0 / 8 above the hair and 0 below the footwear.
// Those branches could not match a receipt, so ajv rejected all seventeen live editorial
// receipts on the standard [74, 78] / 8 / 2 and editorial QA was validating nothing.
//
// So this script is the only writer of those literals. It asks the same resolver the QA
// path asks, one row per lock, and splices the result into each schema's `framingLock`
// definition; test/contracts/scene-framing-lock-schema.test.js fails when a committed
// schema stops matching what this prints.
//
//   node tools/generate-framing-lock-schema.mjs           rewrites the three schemas
//   node tools/generate-framing-lock-schema.mjs --check    reports drift, writes nothing

import assert from 'node:assert/strict';
import path from 'node:path';
import { readFile, writeFile } from 'node:fs/promises';
import { editorialFramingLock, sceneFramingLock } from '../src/web/scene-contract.js';
import { EDITORIAL_SHOT_SLOTS } from '../src/web/editorial-shoot-contract.js';

const ROOT = path.resolve(import.meta.dirname, '..');
const SCHEMA_DIR = path.join(ROOT, 'schemas');

export const GENERATED_KEY = 'framingLock';
const POINTER = `#/$defs/${GENERATED_KEY}/$defs`;
// Any id the resolver will answer for. Only the shape matters: it reads the `editorial.`
// prefix and the shot-slot suffix and nothing between them.
const STANDARD_PROBE_ID = 'std.framing.lock.probe';
const EDITORIAL_PROBE_MODE_ID = 'editorial.framing.lock.probe';
const EDITORIAL_ID_PREFIX = '^editorial\\.';
const ID_BODY = '[A-Za-z0-9._-]+';
// The three numbers a receipt records as the lock it was judged against. A row is selected
// by them, which is what lets the bands be checked at a pointer that cannot see the preset
// id — `#/$defs/attempt` on its own, as test/contracts/scene-job-framing-outcomes does.
const DECLARED_KEYS = Object.freeze([
  'expected_subject_height_percent',
  'minimum_clear_space_above_hair_percent',
  'minimum_clear_space_below_footwear_percent',
]);
const WAIVER_KEY = 'clear_space_above_hair_waived_by_full_head';

const COMMENT = 'GENERATED by tools/generate-framing-lock-schema.mjs from sceneFramingLock()'
  + ' in src/web/scene-contract.js. Do not hand-edit: run the script.'
  + ' evidenceRows selects a lock row by the three numbers the receipt declares;'
  + ' passingEvidenceRows adds the measurements that row makes passable;'
  + ' the allOf branches pin the declared row to the preset the scene was shot under.';

function declared(lock) {
  return {
    expected_subject_height_percent: { const: [...lock.subject] },
    minimum_clear_space_above_hair_percent: { const: lock.above },
    minimum_clear_space_below_footwear_percent: { const: lock.below },
  };
}

// Headroom is only ever waived where it is measured against a required head and the lock
// calls it advisory, so on every other row the flag is pinned false rather than merely
// permitted. Left permitted it was decoration: a standard receipt could have claimed the
// editorial allowance and nothing would have contradicted it.
function waivable(lock) {
  return lock.aboveIsAdvisoryWhenHeadVisible === true && lock.head === true;
}

function evidenceRow(lock) {
  const properties = declared(lock);
  if (!waivable(lock)) properties[WAIVER_KEY] = { const: false };
  return { properties, required: [...DECLARED_KEYS] };
}

function passingEvidenceRow(lock) {
  const properties = {
    ...declared(lock),
    subject_height_percent: { minimum: lock.subject[0], maximum: lock.subject[1] },
  };
  if (lock.head) properties.full_head_visible = { const: true };
  if (lock.footwear) {
    properties.full_footwear_visible = { const: true };
    properties.clear_space_below_footwear_percent = { minimum: lock.below };
  }
  const row = { properties, required: [...DECLARED_KEYS] };
  if (!waivable(lock)) {
    properties[WAIVER_KEY] = { const: false };
    if (lock.head) properties.clear_space_above_hair_percent = { minimum: lock.above };
    return row;
  }
  // The waiver is what carries the one passing frame in the delivered series
  // (clean_identity_hero, 3.2813% of headroom against a 6% minimum), and until now that
  // frame could pass without saying so. A receipt under the minimum has to state the
  // waiver and the whole head it rests on; a receipt over the minimum has nothing to
  // waive and may not claim it.
  row.anyOf = [
    {
      properties: {
        clear_space_above_hair_percent: { minimum: lock.above },
        [WAIVER_KEY]: { const: false },
      },
    },
    {
      properties: {
        clear_space_above_hair_percent: { exclusiveMaximum: lock.above },
        full_head_visible: { const: true },
        [WAIVER_KEY]: { const: true },
      },
      required: [WAIVER_KEY],
    },
  ];
  return row;
}

// One walk of the resolver the live QA path calls, in place of seven hand-kept tables.
export function framingLockRows() {
  const rows = [['standard', sceneFramingLock(STANDARD_PROBE_ID)]];
  for (const slot of EDITORIAL_SHOT_SLOTS) {
    const resolved = sceneFramingLock(`${EDITORIAL_PROBE_MODE_ID}.${slot}`);
    // A slot the resolver has lost does not throw, it lands on the standard lock — which
    // would silently judge an art crop as a fitting shot, the exact failure the whole
    // editorial lock exists to prevent.
    assert.equal(
      resolved,
      editorialFramingLock(slot),
      `sceneFramingLock does not resolve ${slot} to its editorial lock`,
    );
    rows.push([slot, resolved]);
  }
  // Rows are told apart by the triple alone, so two locks sharing one triple would make
  // the selection ambiguous and judge one slot by another slot's measurements.
  const triples = new Set(rows.map(([, lock]) => JSON.stringify(declared(lock))));
  assert.equal(
    triples.size,
    rows.length,
    'two framing locks declare the same expected range and minimums',
  );
  return rows;
}

const TARGETS = Object.freeze([
  {
    file: 'scene-qa-receipt.schema.json',
    // The asset result carries preset_id and framing_evidence side by side.
    presetIs: (matcher) => ({ properties: { preset_id: matcher }, required: ['preset_id'] }),
    declaresRow: (row) => ({ properties: { framing_evidence: row } }),
  },
  {
    file: 'scene-job.schema.json',
    presetIs: (matcher) => ({
      properties: {
        bindings: {
          properties: { preset: { properties: { preset_id: matcher }, required: ['preset_id'] } },
          required: ['preset'],
        },
      },
      required: ['bindings'],
    }),
    declaresRow: (row) => ({
      properties: {
        qa: { properties: { framing_evidence: row } },
        attempts: {
          items: {
            properties: {
              qa: { properties: { framing_evidence: row } },
              normalization: { properties: { trigger_framing_evidence: row } },
            },
          },
        },
      },
    }),
  },
  {
    file: 'scene-production-receipt.schema.json',
    presetIs: (matcher) => ({
      properties: { preset: { properties: { preset_id: matcher }, required: ['preset_id'] } },
      required: ['preset'],
    }),
    declaresRow: (row) => ({
      properties: {
        qa: { properties: { framing_evidence: row } },
        attempt_history: { items: { properties: { qa: { properties: { framing_evidence: row } } } } },
        generation: {
          properties: { normalization: { properties: { trigger_framing_evidence: row } } },
        },
      },
    }),
  },
]);

export function framingLockFragment(target) {
  const rows = framingLockRows();
  const defs = {
    evidenceRows: { oneOf: rows.map(([, lock]) => evidenceRow(lock)) },
    passingEvidenceRows: { oneOf: rows.map(([, lock]) => passingEvidenceRow(lock)) },
  };
  for (const [key, lock] of rows) defs[`declared_${key}`] = { properties: declared(lock) };
  const allOf = rows.map(([key]) => ({
    if: target.presetIs(key === 'standard'
      ? { not: { pattern: EDITORIAL_ID_PREFIX } }
      : { pattern: `${EDITORIAL_ID_PREFIX}${ID_BODY}\\.${key}$` }),
    then: target.declaresRow({ $ref: `${POINTER}/declared_${key}` }),
  }));
  // Without this an editorial id naming no known slot would be the one path left holding
  // no bands at all, which is how the mode-keyed branches went unnoticed for a whole
  // delivered series.
  allOf.push({
    if: target.presetIs({ pattern: EDITORIAL_ID_PREFIX }),
    then: target.presetIs({ pattern: `\\.(${EDITORIAL_SHOT_SLOTS.join('|')})$` }),
  });
  return { $comment: COMMENT, $defs: defs, allOf };
}

// Splices one `$defs` member in place instead of reserialising the file, so a generated
// number never arrives inside a whole-file reformat that nobody can review.
function replaceDefinition(text, key, value, indent = 4) {
  const opener = `${' '.repeat(indent)}"${key}": `;
  const start = text.indexOf(opener);
  assert.notEqual(start, -1, `${key} must already exist as a $defs member`);
  const valueStart = start + opener.length;
  assert.equal(text[valueStart], '{', `${key} must be an object`);
  let depth = 0;
  let inString = false;
  let escaped = false;
  let valueEnd = -1;
  for (let i = valueStart; i < text.length; i += 1) {
    const character = text[i];
    if (inString) {
      if (escaped) escaped = false;
      else if (character === '\\') escaped = true;
      else if (character === '"') inString = false;
      continue;
    }
    if (character === '"') inString = true;
    else if (character === '{' || character === '[') depth += 1;
    else if (character === '}' || character === ']') {
      depth -= 1;
      if (depth === 0) {
        valueEnd = i + 1;
        break;
      }
    }
  }
  assert.notEqual(valueEnd, -1, `${key} is not a balanced JSON value`);
  const [head, ...rest] = JSON.stringify(value, null, 2).split('\n');
  const rendered = [head, ...rest.map((line) => `${' '.repeat(indent)}${line}`)].join('\n');
  return `${text.slice(0, valueStart)}${rendered}${text.slice(valueEnd)}`;
}

export async function renderSchema(target) {
  const file = path.join(SCHEMA_DIR, target.file);
  const current = await readFile(file, 'utf8');
  return { file, current, next: replaceDefinition(current, GENERATED_KEY, framingLockFragment(target)) };
}

export async function renderAllSchemas() {
  return Promise.all(TARGETS.map((target) => renderSchema(target)));
}

async function main() {
  const check = process.argv.includes('--check');
  const rendered = await renderAllSchemas();
  const drifted = rendered.filter((entry) => entry.current !== entry.next);
  if (check) {
    for (const entry of drifted) process.stdout.write(`DRIFT ${path.basename(entry.file)}\n`);
    if (drifted.length > 0) process.exitCode = 1;
    else process.stdout.write(`${rendered.length} schemas match the framing locks\n`);
    return;
  }
  for (const entry of drifted) {
    await writeFile(entry.file, entry.next);
    process.stdout.write(`wrote ${path.basename(entry.file)}\n`);
  }
  if (drifted.length === 0) process.stdout.write('no changes\n');
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) {
  await main();
}
